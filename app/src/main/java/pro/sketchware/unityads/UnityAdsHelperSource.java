package pro.sketchware.unityads;

/**
 * Generates {@code UnityAdsHelper.java}, the one class added to a project that uses Unity Ads. The blocks only call
 * its static methods, so block code never has to import Unity classes.
 * <p>
 * The output must compile with ECJ at Java 1.7 level: no lambdas, no default methods.
 */
public final class UnityAdsHelperSource {
    public static final String FILE_NAME = "UnityAdsHelper.java";

    private UnityAdsHelperSource() {
    }

    public static String generate(String packageName, UnityAdsConfig config) {
        return TEMPLATE
                .replace("%PACKAGE%", packageName)
                .replace("%GAME_ID%", escape(config.gameId))
                .replace("%TEST_MODE%", String.valueOf(config.testMode))
                .replace("%BANNER%", escape(config.bannerPlacement))
                .replace("%INTERSTITIAL%", escape(config.interstitialPlacement))
                .replace("%REWARDED%", escape(config.rewardedPlacement));
    }

    static String escape(String value) {
        if (value == null) {
            return "";
        }
        return value.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "").replace("\r", "");
    }

    private static final String TEMPLATE = ""
            + "package %PACKAGE%;\n"
            + "\n"
            + "import android.app.Activity;\n"
            + "import android.content.Context;\n"
            + "import android.util.Log;\n"
            + "import android.view.ViewGroup;\n"
            + "\n"
            + "import com.unity3d.ads.IUnityAdsInitializationListener;\n"
            + "import com.unity3d.ads.IUnityAdsLoadListener;\n"
            + "import com.unity3d.ads.IUnityAdsShowListener;\n"
            + "import com.unity3d.ads.UnityAds;\n"
            + "import com.unity3d.ads.UnityAdsShowOptions;\n"
            + "import com.unity3d.services.banners.BannerErrorInfo;\n"
            + "import com.unity3d.services.banners.BannerView;\n"
            + "import com.unity3d.services.banners.UnityBannerSize;\n"
            + "\n"
            + "/** Generated by NWS from the project's Unity Ads settings. Edit the settings, not this file. */\n"
            + "public class UnityAdsHelper {\n"
            + "    private static final String TAG = \"UnityAdsHelper\";\n"
            + "\n"
            + "    public static final String GAME_ID = \"%GAME_ID%\";\n"
            + "    public static final boolean TEST_MODE = %TEST_MODE%;\n"
            + "    public static final String BANNER_PLACEMENT = \"%BANNER%\";\n"
            + "    public static final String INTERSTITIAL_PLACEMENT = \"%INTERSTITIAL%\";\n"
            + "    public static final String REWARDED_PLACEMENT = \"%REWARDED%\";\n"
            + "\n"
            + "    /** Receives the placement ID, or an error message for the failure events. */\n"
            + "    public interface Callback {\n"
            + "        void onEvent(String value);\n"
            + "    }\n"
            + "\n"
            + "    public static Callback onInitComplete;\n"
            + "    public static Callback onInitFailed;\n"
            + "    public static Callback onAdLoaded;\n"
            + "    public static Callback onAdLoadFailed;\n"
            + "    public static Callback onAdClosed;\n"
            + "    public static Callback onAdShowFailed;\n"
            + "    public static Callback onUserRewarded;\n"
            + "\n"
            + "    private static boolean interstitialLoaded;\n"
            + "    private static boolean rewardedLoaded;\n"
            + "    private static BannerView banner;\n"
            + "\n"
            + "    private UnityAdsHelper() {\n"
            + "    }\n"
            + "\n"
            + "    private static void fire(Callback callback, String value) {\n"
            + "        if (callback != null) {\n"
            + "            callback.onEvent(value);\n"
            + "        }\n"
            + "    }\n"
            + "\n"
            + "    public static boolean isInitialized() {\n"
            + "        return UnityAds.isInitialized();\n"
            + "    }\n"
            + "\n"
            + "    public static void initialize(Context context) {\n"
            + "        if (UnityAds.isInitialized()) {\n"
            + "            fire(onInitComplete, \"\");\n"
            + "            return;\n"
            + "        }\n"
            + "        UnityAds.initialize(context.getApplicationContext(), GAME_ID, TEST_MODE, new IUnityAdsInitializationListener() {\n"
            + "            @Override\n"
            + "            public void onInitializationComplete() {\n"
            + "                fire(onInitComplete, \"\");\n"
            + "            }\n"
            + "\n"
            + "            @Override\n"
            + "            public void onInitializationFailed(UnityAds.UnityAdsInitializationError error, String message) {\n"
            + "                Log.e(TAG, \"Initialization failed: \" + error + \" \" + message);\n"
            + "                fire(onInitFailed, String.valueOf(message));\n"
            + "            }\n"
            + "        });\n"
            + "    }\n"
            + "\n"
            + "    public static boolean isInterstitialLoaded() {\n"
            + "        return interstitialLoaded;\n"
            + "    }\n"
            + "\n"
            + "    public static boolean isRewardedLoaded() {\n"
            + "        return rewardedLoaded;\n"
            + "    }\n"
            + "\n"
            + "    public static void loadInterstitial() {\n"
            + "        load(INTERSTITIAL_PLACEMENT);\n"
            + "    }\n"
            + "\n"
            + "    public static void loadRewarded() {\n"
            + "        load(REWARDED_PLACEMENT);\n"
            + "    }\n"
            + "\n"
            + "    private static void load(final String placement) {\n"
            + "        if (!UnityAds.isInitialized()) {\n"
            + "            Log.w(TAG, \"Load requested before initialization: \" + placement);\n"
            + "            fire(onAdLoadFailed, \"Unity Ads is not initialized\");\n"
            + "            return;\n"
            + "        }\n"
            + "        UnityAds.load(placement, new IUnityAdsLoadListener() {\n"
            + "            @Override\n"
            + "            public void onUnityAdsAdLoaded(String placementId) {\n"
            + "                setLoaded(placementId, true);\n"
            + "                fire(onAdLoaded, placementId);\n"
            + "            }\n"
            + "\n"
            + "            @Override\n"
            + "            public void onUnityAdsFailedToLoad(String placementId, UnityAds.UnityAdsLoadError error, String message) {\n"
            + "                Log.e(TAG, \"Load failed for \" + placementId + \": \" + error + \" \" + message);\n"
            + "                setLoaded(placementId, false);\n"
            + "                fire(onAdLoadFailed, String.valueOf(message));\n"
            + "            }\n"
            + "        });\n"
            + "    }\n"
            + "\n"
            + "    private static void setLoaded(String placementId, boolean loaded) {\n"
            + "        if (INTERSTITIAL_PLACEMENT.equals(placementId)) {\n"
            + "            interstitialLoaded = loaded;\n"
            + "        }\n"
            + "        if (REWARDED_PLACEMENT.equals(placementId)) {\n"
            + "            rewardedLoaded = loaded;\n"
            + "        }\n"
            + "    }\n"
            + "\n"
            + "    public static void showInterstitial(Activity activity) {\n"
            + "        show(activity, INTERSTITIAL_PLACEMENT);\n"
            + "    }\n"
            + "\n"
            + "    public static void showRewarded(Activity activity) {\n"
            + "        show(activity, REWARDED_PLACEMENT);\n"
            + "    }\n"
            + "\n"
            + "    private static void show(Activity activity, String placement) {\n"
            + "        if (!UnityAds.isInitialized()) {\n"
            + "            fire(onAdShowFailed, \"Unity Ads is not initialized\");\n"
            + "            return;\n"
            + "        }\n"
            + "        UnityAds.show(activity, placement, new UnityAdsShowOptions(), new IUnityAdsShowListener() {\n"
            + "            @Override\n"
            + "            public void onUnityAdsShowFailure(String placementId, UnityAds.UnityAdsShowError error, String message) {\n"
            + "                Log.e(TAG, \"Show failed for \" + placementId + \": \" + error + \" \" + message);\n"
            + "                setLoaded(placementId, false);\n"
            + "                fire(onAdShowFailed, String.valueOf(message));\n"
            + "            }\n"
            + "\n"
            + "            @Override\n"
            + "            public void onUnityAdsShowStart(String placementId) {\n"
            + "            }\n"
            + "\n"
            + "            @Override\n"
            + "            public void onUnityAdsShowClick(String placementId) {\n"
            + "            }\n"
            + "\n"
            + "            @Override\n"
            + "            public void onUnityAdsShowComplete(String placementId, UnityAds.UnityAdsShowCompletionState state) {\n"
            + "                setLoaded(placementId, false);\n"
            + "                if (REWARDED_PLACEMENT.equals(placementId) && state == UnityAds.UnityAdsShowCompletionState.COMPLETED) {\n"
            + "                    fire(onUserRewarded, placementId);\n"
            + "                }\n"
            + "                fire(onAdClosed, placementId);\n"
            + "            }\n"
            + "        });\n"
            + "    }\n"
            + "\n"
            + "    /** Shows a 320x50 banner inside {@code container}, which must be a layout (LinearLayout, FrameLayout...). */\n"
            + "    public static void showBanner(Activity activity, android.view.View container) {\n"
            + "        if (!(container instanceof ViewGroup)) {\n"
            + "            Log.e(TAG, \"The banner container must be a layout\");\n"
            + "            return;\n"
            + "        }\n"
            + "        if (!UnityAds.isInitialized()) {\n"
            + "            fire(onAdLoadFailed, \"Unity Ads is not initialized\");\n"
            + "            return;\n"
            + "        }\n"
            + "        hideBanner();\n"
            + "        banner = new BannerView(activity, BANNER_PLACEMENT, new UnityBannerSize(320, 50));\n"
            + "        banner.setListener(new BannerView.IListener() {\n"
            + "            @Override\n"
            + "            public void onBannerLoaded(BannerView bannerAdView) {\n"
            + "                fire(onAdLoaded, BANNER_PLACEMENT);\n"
            + "            }\n"
            + "\n"
            + "            @Override\n"
            + "            public void onBannerShown(BannerView bannerAdView) {\n"
            + "            }\n"
            + "\n"
            + "            @Override\n"
            + "            public void onBannerClick(BannerView bannerAdView) {\n"
            + "            }\n"
            + "\n"
            + "            @Override\n"
            + "            public void onBannerFailedToLoad(BannerView bannerAdView, BannerErrorInfo errorInfo) {\n"
            + "                Log.e(TAG, \"Banner failed to load: \" + errorInfo.errorMessage);\n"
            + "                fire(onAdLoadFailed, String.valueOf(errorInfo.errorMessage));\n"
            + "            }\n"
            + "\n"
            + "            @Override\n"
            + "            public void onBannerLeftApplication(BannerView bannerView) {\n"
            + "            }\n"
            + "        });\n"
            + "        ((ViewGroup) container).addView(banner);\n"
            + "        banner.load();\n"
            + "    }\n"
            + "\n"
            + "    public static void hideBanner() {\n"
            + "        if (banner != null) {\n"
            + "            if (banner.getParent() instanceof ViewGroup) {\n"
            + "                ((ViewGroup) banner.getParent()).removeView(banner);\n"
            + "            }\n"
            + "            banner.destroy();\n"
            + "            banner = null;\n"
            + "        }\n"
            + "    }\n"
            + "}\n";
}
