    public static String generate(String packageName, UnityAdsConfig config) {
        return TEMPLATE
                .replace("%PACKAGE%", packageName)
                .replace("%GAME_ID%", escape(config.gameId))
                .replace("%TEST_MODE%", String.valueOf(config.testMode))
                .replace("%AUTO_BANNER%", String.valueOf(config.autoBanner))
                .replace("%BANNER%", escape(config.bannerPlacement))
                .replace("%INTERSTITIAL%", escape(config.interstitialPlacement))
                .replace("%REWARDED%", escape(config.rewardedPlacement));
    }

    static String escape(String value) {
        if (value == null) {
            return "";
        }
        return value.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "").replace("\r", "");
    }

